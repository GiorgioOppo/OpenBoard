#!/usr/bin/env python3
"""Build the dependency-free browser catalogue from reviewed translation files."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PARTS = ('common', 'core', 'planning', 'workflows', 'errors', 'extra-errors', 'counts', 'activity', 'experience', 'capacity')


def build():
    catalog = {}
    for part in PARTS:
        messages = json.loads((ROOT / 'locales' / f'{part}.json').read_text())
        for source, translations in messages.items():
            if not isinstance(source, str) or not source.strip() or source != ' '.join(source.split()):
                raise ValueError(f'{part}: noncanonical source: {source!r}')
            if not isinstance(translations, list) or len(translations) != 6:
                raise ValueError(f'{part}: six translations required: {source!r}')
            placeholders = sorted(re.findall(r'\{\w+\}', source))
            for translation in translations:
                if not isinstance(translation, str) or not translation.strip():
                    raise ValueError(f'{part}: empty translation: {source!r}')
                if sorted(re.findall(r'\{\w+\}', translation)) != placeholders:
                    raise ValueError(f'{part}: placeholder mismatch: {source!r}: {translation!r}')
            # Shared terms follow a stable priority: common, core, then modules.
            catalog.setdefault(source, translations)
    body = json.dumps(catalog, ensure_ascii=False, sort_keys=True, indent=2)
    return ('/* Generated by scripts/build-locales.py. Edit locales/*.json.\n'
            ' * Columns: English, French, Spanish, German, Simplified Chinese, Japanese. */\n'
            "'use strict';\nglobalThis.OpenBoardLocales = Object.freeze(" + body + ');\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the generated bundle is stale')
    args = parser.parse_args()
    result = build()
    target = ROOT / 'web/locales.js'
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit('Locale bundle is stale. Run python3 scripts/build-locales.py')
    else:
        target.write_text(result)
